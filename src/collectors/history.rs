/// Directories that hold documentation, examples, benchmarks, fixtures or
/// tooling rather than shipped code, on top of conventional test paths.
const NON_PRODUCTION_DIRECTORIES: &[&str] = &[
    "__fixtures__",
    "bench",
    "benchmark",
    "benchmarks",
    "doc",
    "docs",
    "docs_src",
    "e2e",
    "example",
    "examples",
    "fixture",
    "fixtures",
    "playground",
    "scripts",
];

/// Whether a changed path is shipped code. Test code, documentation, examples,
/// benchmarks, fixtures, scripts and tool configuration such as
/// `vitest.config.ts` are neither owners nor responsibilities, and no history
/// finding is located on them.
fn production_path(path: &str) -> bool {
    let path_ref = Path::new(path);
    let name = path_ref
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or_default();
    !conventional_test_path(path)
        && !path_ref.parent().is_some_and(non_production_directory)
        && !name.contains(".config.")
        && !matches!(name, "setup.py" | "noxfile.py")
}

fn non_production_directory(directory: &Path) -> bool {
    directory
        .components()
        .filter_map(|component| component.as_os_str().to_str())
        .any(|component| {
            NON_PRODUCTION_DIRECTORIES.contains(&component)
                || component.ends_with("-tests")
                || component.ends_with("_tests")
        })
}

const GENERATED_MARKERS: &[&str] = &[
    "@generated",
    "do not edit",
    "auto generated",
    "auto-generated",
    "autogenerated",
    "automatically generated",
    "generated by",
];

/// Whether a comment in the first five lines marks the file as generated
/// output, which is regenerated rather than restructured.
fn generated(source: &str) -> bool {
    source
        .lines()
        .take(5)
        .map(str::trim_start)
        .filter(|line| {
            ["#", "//", "/*", "*"]
                .iter()
                .any(|token| line.starts_with(token))
        })
        .any(|line| {
            let line = line.to_ascii_lowercase();
            GENERATED_MARKERS.iter().any(|marker| line.contains(marker))
        })
}

/// Whether a history finding may be located on a file.
fn locatable(path: &str, source: &str) -> bool {
    production_path(path) && !generated(source)
}

/// Conventional-commit types that, by convention, carry no production change.
const SWEEP_TYPES: &[&str] = &[
    "build", "chore", "ci", "doc", "docs", "fmt", "format", "lint", "style", "test", "typo",
];
/// Words that name a formatter, linter, type checker, typing, whitespace, spelling or
/// MSRV sweep.
const SWEEP_WORDS: &[&str] = &[
    "__future__",
    "clippy",
    "codespell",
    "fmt",
    "formatting",
    "isort",
    "lint",
    "lints",
    "msrv",
    "mypy",
    "oxfmt",
    "prettier",
    "pyright",
    "reformat",
    "ruff",
    "rustfmt",
    "spelling",
    "typing",
    "typo",
    "typos",
    "whitespace",
    "ws",
];
/// Leading words of version-bump and formatting commits.
const SWEEP_LEADS: &[&str] = &["bump", "format", "reformat"];
/// Phrases that name a type-annotation sweep or a supported-Python-version
/// change, the Python counterpart of an MSRV sweep, as whole words.
const SWEEP_PHRASES: &[&[&str]] = &[
    &["type", "hint"],
    &["type", "annotation"],
    &["support", "for", "python"],
    &["python", "version"],
];
/// Verbs that make a sweep phrase the object of the commit, as in "add type hints".
const PHRASE_LEADS: &[&str] = &[
    "add", "correct", "drop", "fix", "improve", "remove", "update",
];
/// Words allowed between a phrase lead and its phrase, as in "drop end of life
/// python versions".
const PHRASE_FILLERS: &[&str] = &[
    "all",
    "broken",
    "deprecated",
    "end",
    "eol",
    "incorrect",
    "life",
    "missing",
    "more",
    "of",
    "old",
    "outdated",
    "some",
    "the",
    "unsupported",
    "wrong",
];

/// Whether a commit subject names a mechanical sweep: a no-production-change
/// conventional type, a version bump or format lead, a formatter, linter,
/// type-checker, typing, whitespace, spelling or MSRV keyword, or a
/// type-annotation or supported-Python-version phrase.
fn mechanical_subject(subject: &str) -> bool {
    let subject = subject
        .trim_start_matches(|c: char| !c.is_ascii_alphanumeric() && c != '_')
        .to_ascii_lowercase();
    let words = subject
        .split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
        .filter(|word| !word.is_empty())
        .collect::<Vec<_>>();
    words.first().is_some_and(|lead| SWEEP_LEADS.contains(lead))
        || conventional_type(&subject).is_some_and(|kind| SWEEP_TYPES.contains(&kind))
        || words.iter().any(|word| SWEEP_WORDS.contains(word))
        || sweep_phrase(&words)
}

/// Whether `words` hold a sweep phrase, each word singular or plural, that a
/// phrase lead opens: "add missing type hints" is a sweep, while "fix crash when
/// resolving type hints" and "show prototype hints" are not.
fn sweep_phrase(words: &[&str]) -> bool {
    SWEEP_PHRASES.iter().any(|phrase| {
        words
            .windows(phrase.len())
            .enumerate()
            .any(|(start, window)| {
                window
                    .iter()
                    .zip(*phrase)
                    .all(|(word, part)| word == part || word.strip_suffix('s') == Some(part))
                    && words[..start]
                        .iter()
                        .rev()
                        .find(|word| !PHRASE_FILLERS.contains(word))
                        .is_some_and(|lead| PHRASE_LEADS.contains(lead))
            })
    })
}

/// The type of a conventional-commit subject such as `chore(deps)!: ...`.
fn conventional_type(subject: &str) -> Option<&str> {
    let end = subject.find(|c: char| !c.is_ascii_alphabetic())?;
    let (kind, rest) = subject.split_at(end);
    let rest = match rest.strip_prefix('(') {
        Some(scoped) => &scoped[scoped.find(')')? + 1..],
        None => rest,
    };
    rest.trim_start_matches('!')
        .starts_with(':')
        .then_some(kind)
}

/// The quoted subject after `marker` (lowercase), up to the last quote.
fn quoted_after<'s>(subject: &'s str, marker: &str) -> Option<&'s str> {
    let start = subject.to_ascii_lowercase().find(marker)? + marker.len();
    let end = subject.rfind('"')?;
    subject.get(start..end)
}

/// The subject a revert commit undoes. Git's `Reapply "X"` undoes `Revert "X"`.
fn revert_target(subject: &str) -> Option<String> {
    quoted_after(subject, "revert \"")
        .map(str::to_string)
        .or_else(|| {
            quoted_after(subject, "reapply \"").map(|reapplied| format!("Revert \"{reapplied}\""))
        })
}

/// A commit touching at least this many production files, and at least a
/// tenth of them, is a repository-wide sweep rather than one logical change.
const BROAD_SWEEP_MINIMUM_FILES: usize = 20;

/// The commits that count as logical changes. The initial import, mechanical
/// sweeps, reverts, and changes reverted inside the window are discounted; a
/// change that is reverted and then re-applied counts once.
struct Changes<'a> {
    reverted: BTreeSet<String>,
    broad: usize,
    commits: Vec<&'a HistoryCommit>,
}

impl<'a> Changes<'a> {
    fn new(input: &'a Input) -> Self {
        let production = input
            .files
            .keys()
            .filter(|path| production_path(path))
            .count();
        let mut changes = Self {
            reverted: input
                .history
                .commits
                .iter()
                .filter_map(|commit| revert_target(&commit.subject))
                .collect(),
            broad: BROAD_SWEEP_MINIMUM_FILES.max(production / 10),
            commits: Vec::new(),
        };
        changes.commits = input
            .history
            .commits
            .iter()
            .filter(|commit| !commit.root && changes.counts(commit))
            .collect();
        changes
    }

    fn counts(&self, commit: &HistoryCommit) -> bool {
        !mechanical_subject(&commit.subject)
            && revert_target(&commit.subject).is_none()
            && !self.reverted_away(&commit.subject)
            && commit
                .files
                .iter()
                .filter(|path| production_path(path))
                .count()
                < self.broad
    }

    fn reverted_away(&self, subject: &str) -> bool {
        self.reverted.contains(subject) && !self.reverted.contains(&format!("Revert \"{subject}\""))
    }
}

/// Assigns each changed production path to the module that owns it: the first
/// path component below its implementation root, after a conventional
/// `src`/`lib` directory and a top-level Python package. A file directly in that
/// root is its own module, unless its directory holds no production
/// subdirectory: such a flat directory is one module. Without this every file
/// in a single-package repository would share one owner.
struct Owners<'a> {
    roots: Vec<&'a str>,
    files: &'a BTreeMap<String, String>,
    flat: BTreeSet<&'a Path>,
}

impl<'a> Owners<'a> {
    fn new(input: &'a Input) -> Self {
        Self {
            roots: input
                .implementations
                .iter()
                .filter_map(|implementation| implementation.root.as_deref())
                .filter(|root| *root != ".")
                .collect(),
            files: &input.files,
            flat: flat_directories(&input.files),
        }
    }

    fn of(&self, path: &str) -> String {
        let root = self
            .roots
            .iter()
            .filter(|root| Path::new(path).starts_with(root))
            .max_by_key(|root| Path::new(root).components().count());
        let mut prefix = root.map_or_else(PathBuf::new, PathBuf::from);
        let mut rest = Path::new(path)
            .strip_prefix(&prefix)
            .unwrap_or(Path::new(path))
            .components()
            .filter_map(|component| component.as_os_str().to_str())
            .collect::<Vec<_>>();
        if rest.len() > 1 && matches!(rest[0], "src" | "lib") {
            prefix.push(rest.remove(0));
        }
        if rest.len() > 1 && self.python_package(&prefix.join(rest[0])) {
            rest.remove(0);
        }
        match rest.as_slice() {
            [] => "unowned".into(),
            [file] => self.flat_owner(path).unwrap_or_else(|| {
                Path::new(file)
                    .file_stem()
                    .and_then(|stem| stem.to_str())
                    .unwrap_or(file)
                    .into()
            }),
            [owner, ..] => (*owner).into(),
        }
    }

    fn flat_owner(&self, path: &str) -> Option<String> {
        let directory = Path::new(path)
            .parent()
            .filter(|directory| self.flat.contains(directory))?;
        directory.to_str().map(str::to_string)
    }

    fn python_package(&self, directory: &Path) -> bool {
        directory
            .join("__init__.py")
            .to_str()
            .is_some_and(|marker| self.files.contains_key(marker))
    }
}

/// Non-empty directories that directly hold production files but have no
/// production file in any subdirectory.
fn flat_directories(files: &BTreeMap<String, String>) -> BTreeSet<&Path> {
    let parents = files
        .keys()
        .filter(|path| production_path(path))
        .filter_map(|path| Path::new(path).parent())
        .filter(|parent| !parent.as_os_str().is_empty())
        .collect::<BTreeSet<_>>();
    let nested = parents
        .iter()
        .flat_map(|parent| parent.ancestors().skip(1))
        .collect::<BTreeSet<_>>();
    parents.difference(&nested).copied().collect()
}

/// Each changed production path's owner, resolved once per scan so
/// commit-sized loops only look owners up.
struct Ownership<'a> {
    by_path: BTreeMap<&'a str, String>,
}

impl<'a> Ownership<'a> {
    fn new(input: &'a Input) -> Self {
        let owners = Owners::new(input);
        Self {
            by_path: input
                .history
                .commits
                .iter()
                .flat_map(|commit| &commit.files)
                .filter(|path| production_path(path))
                .map(|path| (path.as_str(), owners.of(path)))
                .collect(),
        }
    }

    /// The owners of the production paths among `paths`.
    fn owners<'p>(&self, paths: impl Iterator<Item = &'p String>) -> BTreeSet<&str> {
        paths
            .filter_map(|path| self.by_path.get(path.as_str()).map(String::as_str))
            .collect()
    }
}

pub(super) fn divergent_change(input: &Input) -> Vec<Observation> {
    if !input.history.available {
        return Vec::new();
    }
    let changes = Changes::new(input);
    let ownership = Ownership::new(input);
    input
        .files
        .iter()
        .filter(|(path, source)| locatable(path, source))
        .filter_map(|(path, source)| {
            let touching = changes
                .commits
                .iter()
                .filter(|commit| commit.files.contains(path))
                .collect::<Vec<_>>();
            if touching.is_empty() {
                return None;
            }
            let responsibilities = ownership.owners(
                touching
                    .iter()
                    .flat_map(|commit| commit.files.iter())
                    .filter(|changed| *changed != path),
            );
            Some(observation(
                format!("{path}::git-change-profile"),
                location_at(path, source, 0),
                [
                    ("changes", touching.len() as u64),
                    ("responsibilities", responsibilities.len() as u64),
                ],
                json!({
                    "collector": "git_cochange_responsibilities_v2",
                    "history_limit": 200,
                    "commit_ids": touching.iter().map(|commit| &commit.id).collect::<Vec<_>>(),
                    "responsibilities": responsibilities,
                }),
            ))
        })
        .collect()
}

pub(super) fn shotgun_surgery(input: &Input) -> Vec<Observation> {
    if !input.history.available {
        return Vec::new();
    }
    let changes = Changes::new(input);
    let ownership = Ownership::new(input);
    changes
        .commits
        .iter()
        .filter_map(|commit| {
            let owners = ownership.owners(commit.files.iter());
            let (anchor, source) = commit.files.iter().find_map(|path| {
                input
                    .files
                    .get_key_value(path)
                    .filter(|(path, source)| locatable(path, source))
            })?;
            Some(observation(
                format!("git:{}", commit.id),
                location_at(anchor, source, 0),
                [("owners", owners.len() as u64)],
                json!({
                    "collector": "git_commit_owner_fanout_v2",
                    "history_limit": 200,
                    "commit_id": commit.id,
                    "owners": owners,
                    "changed_files": commit.files,
                }),
            ))
        })
        .collect()
}

